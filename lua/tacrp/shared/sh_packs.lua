TacRP.Packs = {}
TacRP.PackOrder = { --[[
	[1] = "tacrp",
	[2] = "extras",
	[3] = "interops",
]] }

TacRP.ClassToPack = { --[[
    ["tacrp_ak47"] = "tacrp",
]] }

-- as to not reinsert into packorder
local registered = { --[[
	["interops"] = true,
]] }

function TacRP.RegisterPack(pack_id, title, weapon_array, sortorder)
	local weapon_lookup = {}
	for _, classname in ipairs(weapon_array) do
		weapon_lookup[classname] = true
		TacRP.ClassToPack[classname] = pack_id
	end
	TacRP.Packs[pack_id] = {
		Title = title,
		SortOrder = sortorder,
		Weapons = weapon_lookup,
		WeaponsArray = weapon_array,
	}
	-- resort packorder
	if not registered[pack_id] then
		table.insert(TacRP.PackOrder, pack_id)
		registered[pack_id] = true
	end
	table.sort( TacRP.PackOrder, function(a, b)
		return TacRP.Packs[a].SortOrder < TacRP.Packs[b].SortOrder
	end)
end

